#!/usr/bin/env python3
"""Write the MakerWorld fixed-gear upload for the Embosser Version 2 listing.

MakerWorld's Parametric Model Maker takes exactly one .scad file and no mesh
files, so the fused Version 2 roller - which imports assets/v2_gears_a.stl and
assets/v2_gears_b.stl - draws no gears there. This script writes
makerworld/Braille_Cylinder_STL_Generator_MakerWorld_v2_Fixed_Gears.scad from
the standard Version 2 upload and the two meshes:

* its own header;
* integrated_gears switched On and kept out of the Customizer;
* the cylinder size and the four key clearances moved into the Hidden tab:
  the gears fit only the 30.8 x 54 mm barrel, and a fused roller has no keyed
  holes for the clearances to size;
* the one import() replaced by polyhedron() on the meshes, which are appended
  as OpenSCAD functions. Each coordinate is written as the shortest decimal
  that reads back as the STL's own float32 value, and each STL triangle becomes
  one face with its winding reversed (STL lists a face counter-clockwise seen
  from outside, polyhedron() clockwise), so the solid is the asset itself.

Usage:
    python scripts/build_makerworld_fixed_gears.py           # write the file
    python scripts/build_makerworld_fixed_gears.py --check   # exit 1 if stale

Standard library only. License: PolyForm Noncommercial 1.0.0
"""

from __future__ import annotations

import argparse
import struct
import sys
from pathlib import Path
from typing import List, Optional, Sequence, Tuple

ROOT = Path(__file__).resolve().parent.parent
SOURCE = ROOT / "makerworld" / "Braille_Cylinder_STL_Generator_MakerWorld_v2.scad"
TARGET = ROOT / "makerworld" / "Braille_Cylinder_STL_Generator_MakerWorld_v2_Fixed_Gears.scad"
MESHES = (
    ("v2_gears_a_mesh", ROOT / "assets" / "v2_gears_a.stl"),
    ("v2_gears_b_mesh", ROOT / "assets" / "v2_gears_b.stl"),
)

MESH_BEGIN = "// ==== BEGIN GEAR MESHES (generated by scripts/build_makerworld_fixed_gears.py) ===="
MESH_END = "// ==== END GEAR MESHES ===="
POINTS_PER_LINE = 8
FACES_PER_LINE = 12

Vertex = Tuple[float, float, float]

TITLE = (
    "// Braille Cylinder STL Generator — Embosser Version 2 (OpenSCAD) — MakerWorld Single-File Build\n",
    "// Braille Cylinder STL Generator — Embosser Version 2 (OpenSCAD) — MakerWorld Fixed Gears Build\n",
)

HEADER_START = "// MAKERWORLD SINGLE-FILE BUILD — EMBOSSER VERSION 2\n"
HEADER_END = "//  maintainer re-sync procedure.\n//\n"
HEADER = """// MAKERWORLD FIXED GEARS BUILD — EMBOSSER VERSION 2
// =============================================================================
//  This file is the fixed-gear upload for the Embosser Version 2 listing on
//  MakerWorld's Parametric Model Maker. Each cylinder comes out as ONE solid
//  roller with its top and bottom drive gears already on: the web app's
//  "Simplified: gears fixed to the cylinders". Fixed gears fit only the
//  Version 2 fixed-gear housing; the standard housing takes the standard
//  cylinders from Braille_Cylinder_STL_Generator_MakerWorld_v2.scad.
//
//  MakerWorld takes no mesh files, so the gears are written into this file:
//  the GEAR MESHES block at the end holds assets/v2_gears_a.stl and
//  assets/v2_gears_b.stl as polyhedron data, every coordinate exact, so a
//  cylinder made here is the desktop build's fused roller. That data makes the
//  file about 3 MB and each render about twice as slow as the standard upload.
//
//  GENERATED - do not edit by hand. scripts/build_makerworld_fixed_gears.py
//  writes it from makerworld/Braille_Cylinder_STL_Generator_MakerWorld_v2.scad
//  and the two meshes, and tests/test_makerworld_fixed_gears.py fails when it
//  is out of date. It differs from that file in four places: this header; the
//  gears switched on; the cylinder size and the four key clearances hidden,
//  because the gears fit only the 30.8 x 54 mm barrel and a fused roller has
//  no keyed holes; and the gear meshes read from the block at the end instead
//  of assets/.
//
"""

ORGANIZATION_LINE = "//  • Expert Mode - Version 2 Keyed Cutouts (one key clearance per gear)\n"

SWITCH = """// The desktop generator ships assets/v2_gears_a.stl and assets/v2_gears_b.stl
// and offers this as a visible dropdown under [Gears]. This
// single-file build has no assets folder, so switching it on would render a
// plate with NO gears and only a console warning to say why. It is declared -
// because tests/test_makerworld_sync.py requires both builds to carry the same
// parameter set, and the geometry body below is byte-identical - but it lives
// in this Hidden tab so the Customizer never offers it. MakerWorld's Parametric
// Model Maker (v1.1.0, checked 2026-08-25) has no way to upload a mesh at all,
// so no version of this build could carry the gears; fused Version 2 rollers
// come from the desktop OpenSCAD build or the web app.
integrated_gears = "Off"; // [Off, On]
"""

SWITCH_ON = """// Fixed gears are what this build is for, so the switch is On and stays out of
// the Customizer. The gear meshes come from the GEAR MESHES block at the end
// of this file, not from assets/.
integrated_gears = "On"; // [Off, On]

// Shown in the other builds, hidden in this one: the gears fit only the
// 30.8 x 54 mm barrel (any other size stops the render, and MakerWorld cannot
// show why), and a fused roller has no keyed holes for the clearances to size.
"""

SIZE_DIALS = """// Cylinder outer diameter in mm. The Version 2 embosser expects a 30.8 mm x 54 mm cylinder. Other sizes still render - the size is a soft preset, not a rule - but they will not fit the Version 2 housing.
cylinder_diameter_mm = 30.8; // [10:0.1:100]
// Cylinder height in mm
cylinder_height_mm = 54; // [20:1:150]
"""

KEYED_TAB = "/* [Expert Mode - Version 2 Keyed Cutouts] */\n"
NEXT_TAB = "/* [Expert Mode - Card Sides] */\n"

IMPORT = '        import(emboss ? "assets/v2_gears_a.stl" : "assets/v2_gears_b.stl");\n'
POLYHEDRON = (
    "        let (mesh = emboss ? v2_gears_a_mesh() : v2_gears_b_mesh())\n"
    "            polyhedron(points = mesh[0], faces = mesh[1], convexity = 10);\n"
)


def read_stl(path: Path) -> List[Tuple[Vertex, Vertex, Vertex]]:
    """A binary STL's triangles, as the float32 values widened to Python floats."""
    data = path.read_bytes()
    count = struct.unpack_from("<I", data, 80)[0]
    if len(data) != 84 + 50 * count:
        raise ValueError(f"{path.name} is not a binary STL of {count} triangles")
    triangles = []
    for i in range(count):
        v = struct.unpack_from("<9f", data, 84 + 50 * i + 12)
        triangles.append((v[0:3], v[3:6], v[6:9]))
    return triangles


def number(x: float) -> str:
    text = repr(x)
    if text.endswith(".0"):
        text = text[:-2]
    return "0" if text == "-0" else text


def mesh_function(name: str, triangles) -> str:
    index = {}
    points: List[Vertex] = []
    faces = []
    for triangle in triangles:
        ids = []
        for vertex in triangle:
            if vertex not in index:
                index[vertex] = len(points)
                points.append(vertex)
            ids.append(index[vertex])
        faces.append((ids[0], ids[2], ids[1]))
    point_text = ["[%s,%s,%s]" % tuple(number(c) for c in p) for p in points]
    face_text = ["[%d,%d,%d]" % f for f in faces]

    def rows(items, per_line):
        return ",\n".join(",".join(items[i : i + per_line]) for i in range(0, len(items), per_line))

    return (
        f"// {name}(): {len(points)} points, {len(faces)} faces.\n"
        f"function {name}() = [[\n{rows(point_text, POINTS_PER_LINE)}\n], [\n"
        f"{rows(face_text, FACES_PER_LINE)}\n]];\n"
    )


def replace_once(text: str, old: str, new: str, what: str) -> str:
    found = text.count(old)
    if found != 1:
        raise ValueError(f"{SOURCE.name}: expected the {what} once, found it {found} times")
    return text.replace(old, new)


def build() -> str:
    text = SOURCE.read_text(encoding="utf-8")
    text = replace_once(text, *TITLE, "title line")

    start = text.index(HEADER_START)
    end = text.index(HEADER_END, start) + len(HEADER_END)
    text = text[:start] + HEADER + text[end:]

    text = replace_once(text, ORGANIZATION_LINE, "", "keyed-cutouts line of the parameter list")
    text = replace_once(text, SIZE_DIALS, "", "cylinder size dials")

    keyed_start = text.index(KEYED_TAB)
    keyed_end = text.index(NEXT_TAB, keyed_start)
    keyed_body = text[keyed_start + len(KEYED_TAB) : keyed_end]
    text = text[:keyed_start] + text[keyed_end:]

    hidden = SWITCH_ON + "\n" + SIZE_DIALS + "\n" + keyed_body.rstrip("\n") + "\n"
    text = replace_once(text, SWITCH, hidden, "hidden gear switch")
    text = replace_once(text, IMPORT, POLYHEDRON, "gear import")

    meshes = "\n".join(mesh_function(name, read_stl(path)) for name, path in MESHES)
    return text.rstrip("\n") + "\n\n" + MESH_BEGIN + "\n" + meshes + MESH_END + "\n"


def main(argv: Optional[Sequence[str]] = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 if the file on disk is out of date")
    args = parser.parse_args(argv)
    built = build()
    if args.check:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else None
        if current != built:
            print(f"{TARGET.relative_to(ROOT).as_posix()} is out of date: run scripts/build_makerworld_fixed_gears.py")
            return 1
        print(f"{TARGET.relative_to(ROOT).as_posix()} is current")
        return 0
    TARGET.write_text(built, encoding="utf-8", newline="\n")
    print(f"{TARGET.relative_to(ROOT).as_posix()}: {len(built.encode('utf-8')) // 1024} KB")
    return 0


if __name__ == "__main__":
    sys.exit(main())
